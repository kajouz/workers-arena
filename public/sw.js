/**
 * WorkersArena service worker — full PWA shell (offline app-shell) + Web Push.
 *
 * Payloads for push come from src/lib/notifications/templates.ts
 * (renderPushPayload): { title, body, url, icon, badge, tag, dir, lang, data }.
 * RTL: the server sets dir/lang per locale so Arabic notifications render RTL.
 *
 * Offline strategy:
 *  - PRECACHE the app shell + top content at install (root, offline page,
 *    manifest, icons, /categories listing, featured worker profiles, and
 *    /search?category=… for every trade so browsing by category works offline.
 *    The PRECACHE_URLS list is auto-generated by scripts/generate-sw-precache.mjs
 *    from the actual featured workers and CATEGORIES — run `npm run precache:sw`
 *    (or it runs automatically via the `prebuild` hook) to keep it in sync.
 *  - NAVIGATIONS (HTML page requests): network-first, fall back to the cached
 *    shell, then to /offline.html — so every route of the app degrades to the
 *    offline page instead of a browser error.
 *  - PROFILE PAGES (/workers/*): network-first like other navigations, but
 *    successful responses are saved to a bounded LRU cache (MAX_PROFILES = 20).
 *    When offline, the profiles cache is checked before the shell, so recently-
 *    browsed workers work fully offline without precaching every slug.
 *  - STATIC ASSETS (same-origin, non-navigation GET): stale-while-revalidate —
 *    respond from cache instantly, refresh in the background. Next.js content
 *    hashes its build chunks, so a redeploy can never serve stale JS.
 *  - /api/* data requests are NEVER cached: the shell works offline, live data
 *    only when online.
 *  - BACKGROUND SYNC: when a search page is served from cache while offline,
 *    a 'refresh-search' sync event is registered.  When the network returns,
 *    the sync handler re-fetches all precached search URLs and updates the
 *    shell cache so results are fresh on next visit.  Clients can also trigger
 *    an immediate refresh by posting { type: 'refresh-search' } to the SW.
 *  - OFFLINE QUEUE + ANALYTICS: leads, reviews, and page-view analytics are
 *    queued in IndexedDB while offline and batch-sent on reconnect via the
 *    registrar's online listener (flushAnalyticsQueue + replayQueue).
 *  - STORAGE BUDGETING: uses navigator.storage.estimate() to monitor disk
 *    usage. When free storage drops below 50 MB, cached profiles are evicted
 *    aggressively. New profiles are only cached if > 25 MB remains free.
 * Bump CACHE_VERSION when the offline shell changes so old caches are purged.
 */

const CACHE_VERSION = "v2";
const SHELL_CACHE = `wa-shell-${CACHE_VERSION}`;
const ASSET_CACHE = `wa-assets-${CACHE_VERSION}`;
const PROFILES_CACHE = `wa-profiles-${CACHE_VERSION}`;
/** Maximum number of recently-visited profiles to keep cached. */
const MAX_PROFILES = 20;
/** Minimum free storage (in bytes) before we start evicting profiles. */
const MIN_FREE_STORAGE = 50 * 1024 * 1024; // 50 MB
/** Pattern matching worker profile navigation URLs. */
const PROFILE_PATH_RE = /^\/workers\/[^/]+$/;

const PRECACHE_URLS = [
  "/",
  "/offline.html",
  "/manifest.webmanifest",
  "/icon.svg",
  "/icons/icon-192.png",
  "/icons/icon-512.png",
  "/icons/maskable-512.png",
  "/icons/apple-touch-icon.png",
  "/categories",
  "/workers/khaled-al-harbi-plumbing",
  "/workers/ali-hassan-carpentry",
  "/workers/omar-al-mutairi-ac-technician",
  "/workers/bilal-mansour-cleaning",
  "/workers/anas-barakat-interior-design",
  "/search?category=plumbing",
  "/search?category=electrical",
  "/search?category=carpentry",
  "/search?category=painting",
  "/search?category=masonry",
  "/search?category=ac-technician",
  "/search?category=satellite-technician",
  "/search?category=mechanic",
  "/search?category=welding",
  "/search?category=blacksmith",
  "/search?category=roofing",
  "/search?category=cleaning",
  "/search?category=movers",
  "/search?category=gardening",
  "/search?category=pest-control",
  "/search?category=locksmith",
  "/search?category=glass-works",
  "/search?category=aluminum-works",
  "/search?category=gypsum-works",
  "/search?category=interior-design",
  "/search?category=construction",
];
/** URLs from PRECACHE_URLS that are search result pages. */
const SEARCH_URLS = PRECACHE_URLS.filter((u) => u.startsWith("/search?"));

/* ── install / activate ─────────────────────────────────────────────────── */
self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(SHELL_CACHE).then((cache) => cache.addAll(PRECACHE_URLS)).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter(
              (k) =>
                k.startsWith("wa-") &&
                k !== SHELL_CACHE &&
                k !== ASSET_CACHE &&
                k !== PROFILES_CACHE
            )
            .map((k) => caches.delete(k))
        )
      )
      .then(() => pruneProfilesCache())
      .then(() => checkStorageBudget())
      .then(() => self.clients.claim())
  );
});

/**
 * Evict the oldest entries from the profiles cache so it stays bounded.
 * Response entries have a `date` header; we use that as the LRU timestamp.
 * If no date header is present, we use the request URL as the key and fall
 * back to entry order (oldest first from cache.keys()).
 */
async function pruneProfilesCache() {
  const cache = await caches.open(PROFILES_CACHE);
  const keys = await cache.keys();
  if (keys.length <= MAX_PROFILES) return;
  // Delete oldest entries first (keys() returns insertion order).
  const toDelete = keys.slice(0, keys.length - MAX_PROFILES);
  await Promise.all(toDelete.map((req) => cache.delete(req)));
}

/**
 * Check storage budget using navigator.storage.estimate() and evict
 * profiles if free storage is below MIN_FREE_STORAGE.  This prevents
 * the PWA from consuming too much disk on storage-constrained devices.
 */
async function checkStorageBudget() {
  if (!navigator.storage || !navigator.storage.estimate) return;
  try {
    const { quota, usage } = await navigator.storage.estimate();
    if (quota == null || usage == null) return;
    const free = quota - usage;
    if (free < MIN_FREE_STORAGE) {
      await evictProfilesForBudget();
    }
  } catch {
    // Storage API not available or errored — silently skip.
  }
}

/**
 * Aggressively evict cached profiles when storage is low.
 * Removes half the profiles cache to free up space quickly.
 */
async function evictProfilesForBudget() {
  const cache = await caches.open(PROFILES_CACHE);
  const keys = await cache.keys();
  if (keys.length === 0) return;
  // Evict the oldest half of the cache
  const evictCount = Math.max(1, Math.floor(keys.length / 2));
  const toEvict = keys.slice(0, evictCount);
  await Promise.all(toEvict.map((req) => cache.delete(req)));
}

/**
 * Check if we can afford to cache a new profile entry.
 * Returns false if storage is critically low.
 */
async function canCacheProfile() {
  if (!navigator.storage || !navigator.storage.estimate) return true;
  try {
    const { quota, usage } = await navigator.storage.estimate();
    if (quota == null || usage == null) return true;
    const free = quota - usage;
    return free >= MIN_FREE_STORAGE / 2; // Allow caching if > 25MB free
  } catch {
    return true;
  }
}

/**
 * Re-fetch all precached search-result URLs and update the shell cache.
 * Called on sync (network restored) and on activation so the most popular
 * search pages are never stale.  Silently swallows individual failures —
 * one broken category shouldn't block the rest.
 */
async function refreshSearchCache() {
  const cache = await caches.open(SHELL_CACHE);
  const results = await Promise.allSettled(
    SEARCH_URLS.map(async (url) => {
      const response = await fetch(url);
      if (response.ok) await cache.put(url, response);
    })
  );
  return results;
}

/**
 * Replay queued offline actions by posting a message to all clients.
 * The actual IndexedDB → /api replay happens in the client context where
 * the offline-queue module lives.  The SW just kicks it off.
 */
async function replayOfflineQueue() {
  const clients = await self.clients.matchAll({ type: "window" });
  for (const client of clients) {
    client.postMessage({ type: "replay-offline-queue" });
  }
}

/* ── background sync: refresh stale search results + replay offline queue ── */
self.addEventListener("sync", (event) => {
  if (event.tag === "refresh-search") {
    event.waitUntil(refreshSearchCache());
  }
  if (event.tag === "replay-offline-queue") {
    event.waitUntil(replayOfflineQueue());
  }
});

/**
 * Client-initiated refresh — the registrar or a page can post a message
 * `{ type: "refresh-search" }` to trigger an immediate background update,
 * or `{ type: "replay-offline-queue" }` to replay queued offline actions.
 */
self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "refresh-search") {
    event.waitUntil(refreshSearchCache());
  }
  if (event.data && event.data.type === "replay-offline-queue") {
    event.waitUntil(replayOfflineQueue());
  }
});
/* ── fetch: offline shell + asset caching ────────────────────────────────── */
self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Data endpoints: never cached — always hit the network.
  if (url.pathname.startsWith("/api/")) return;

  if (request.mode === "navigate") {
    const isProfile = PROFILE_PATH_RE.test(url.pathname);
    event.respondWith(
      fetch(request)
        .then(async (response) => {
          // Cache a successful navigation response as the fresh shell fallback.
          const copy = response.clone();
          caches.open(SHELL_CACHE).then((cache) => cache.put(request.url, copy)).catch(() => {});
          // Profile pages get their own bounded LRU cache for offline access.
          if (isProfile && response.ok) {
            const canCache = await canCacheProfile();
            if (canCache) {
              caches
                .open(PROFILES_CACHE)
                .then((cache) => cache.put(request.url, copy))
                .then(() => pruneProfilesCache())
                .catch(() => {});
            }
          }
          return response;
        })
        .catch(async () => {
          // Profile pages: check the dedicated profiles cache first so
          // recently-browsed workers work fully offline.
          if (isProfile) {
            const profileCached = await caches.match(request.url);
            if (profileCached) return profileCached;
          }
          const cached = await caches.match(request, { ignoreSearch: true });
          if (cached) {
            // Search pages served from cache trigger a background sync
            // so they're fresh next time the network is available.
            if (url.pathname === "/search") {
              self.registration
                .sync.register("refresh-search")
                .catch(() => {});
            }
            return cached;
          }
          const offline = await caches.match("/offline.html");
          if (offline) return offline;
          return new Response("Offline", { status: 503, headers: { "Content-Type": "text/plain" } });
        })
    );
    return;
  }

  // Static assets (JS/CSS/images/fonts): stale-while-revalidate.
  event.respondWith(
    caches.match(request).then((cached) => {
      const network = fetch(request)
        .then((response) => {
          if (response && response.ok && response.type === "basic") {
            const copy = response.clone();
            caches.open(ASSET_CACHE).then((cache) => cache.put(request, copy)).catch(() => {});
          }
          return response;
        })
        .catch(() => cached);
      return cached || network;
    })
  );
});

/* ── push display + notification actions ─────────────────────────────────── */
/** Action buttons for notifications — "view" deep-links, "dismiss" just closes. */
const NOTIFICATION_ACTIONS = [
  { action: "view", title: "View" },
  { action: "dismiss", title: "Dismiss" },
];

self.addEventListener("push", (event) => {
  let data = null;
  try {
    data = event.data ? event.data.json() : null;
  } catch {
    data = null;
  }

  const payload =
    data && typeof data === "object"
      ? data
      : {
          title: "WorkersArena",
          body: event.data ? event.data.text() : "",
          url: "/",
        };

  event.waitUntil(
    self.registration.showNotification(payload.title || "WorkersArena", {
      body: payload.body || "",
      icon: payload.icon || "/icons/icon-192.png",
      badge: payload.badge || "/icons/icon-192.png",
      tag: payload.tag,
      dir: payload.dir || "auto",
      lang: payload.lang || "en",
      data: payload.data || {},
      renotify: payload.tag ? true : undefined,
      // Action buttons give users quick access without opening the panel.
      actions: NOTIFICATION_ACTIONS,
    })
  );
});

self.addEventListener("notificationclick", (event) => {
  const url = (event.notification.data && event.notification.data.url) || "/";

  // "dismiss" action just closes the notification — no navigation.
  if (event.action === "dismiss") {
    event.notification.close();
    return;
  }

  // "view" action (or default click) navigates to the deep link.
  event.notification.close();
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((windowClients) => {
      // Focus an existing tab on the same origin instead of opening a new one.
      for (const client of windowClients) {
        if ("focus" in client) {
          client.navigate(url).catch(() => {});
          return client.focus();
        }
      }
      return self.clients.openWindow(url);
    })
  );
});
